/* -------------------------------------------------------------------------
 * Queries
 * ---------------------------------------------------------------------- */

export function planHasFeature(plan: PlanId, feature: PlanFeature): boolean {
  return PLANS[plan].features.includes(feature);
}

/**
 * Whether a feature can actually be used right now: it must be both sold on
 * the plan AND built. Call this — not `planHasFeature` — at the point of use,
 * so an unshipped capability cannot be switched on by an entitlement alone.
 */
export function featureIsAvailable(plan: PlanId, feature: PlanFeature): boolean {
  return planHasFeature(plan, feature) && !NOT_YET_SHIPPED.includes(feature);
}

export function planLimit<K extends keyof PlanLimits>(plan: PlanId, limit: K): PlanLimits[K] {
  return PLANS[plan].limits[limit];
}

/** USD charged for `n` replies beyond the plan allowance. */
export function overageCostUsd(repliesOverAllowance: number): number {
  if (repliesOverAllowance <= 0) return 0;
  return Math.round(repliesOverAllowance * OVERAGE_USD_PER_REPLY * 100) / 100;
}

/**
 * How many overage replies an account may still generate before its hard cap
 * stops it. Returns 0 when the cap is reached — callers must then refuse to
 * generate and offer human handoff instead.
 */
export function repliesRemainingUnderCap(overageSpentUsd: number, hardCapUsd: number): number {
  const budget = hardCapUsd - overageSpentUsd;
  if (budget <= 0) return 0;
  return Math.floor(budget / OVERAGE_USD_PER_REPLY);
}

/** Total USD billed for a full year on the annual plan. */
export function annualTotalUsd(plan: PlanId): number {
  return PLANS[plan].monthlyUsd * ANNUAL_MONTHS_CHARGED;
}
