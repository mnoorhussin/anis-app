/* -------------------------------------------------------------------------
 * Plan shape
 * ---------------------------------------------------------------------- */

export interface PlanLimits {
  /**
   * AI replies included per billing period. An "AI reply" is one assistant
   * message generated by the model — not a conversation, and not a message
   * sent by a human agent during takeover.
   */
  aiRepliesPerMonth: number;
  /** Workspaces (= assistants). Agencies get many; everyone else gets one. */
  workspaces: number;
  /** Distinct websites that may be crawled as sources, across the account. */
  websites: number;
  /** Team members with dashboard access, including the owner. */
  members: number;
  /** Knowledge sources per workspace (pages, PDFs, text blocks, FAQ sets). */
  sourcesPerWorkspace: number;
  /** Ceiling on total indexed chunks per workspace — the real cost driver. */
  chunksPerWorkspace: number;
  /**
   * Pages fetched in one website crawl. Separate from sourcesPerWorkspace
   * because a single site can be thousands of pages, and each one costs an
   * outbound request against the customer's own server as well as embedding
   * spend.
   */
  pagesPerCrawl: number;
  /**
   * Conversation retention, in days. `null` means "keep until deleted", which
   * we only offer where the customer has configured it deliberately — the
   * privacy page states the actual number.
   */
  retentionDays: number | null;
}

export interface Plan {
  id: PlanId;
  /** Display name. Not translated — the plan names are the same in AR and EN. */
  name: string;
  /** USD per month, billed monthly. */
  monthlyUsd: number;
  /**
   * USD per month when billed annually. The marketing site advertises
   * "2 months free", i.e. an annual bill of 10 × the monthly price.
   */
  annualMonthlyUsd: number;
  limits: PlanLimits;
  features: readonly PlanFeature[];
  /** Highlighted as "Most popular" on the pricing page. */
  popular?: boolean;
}

/** Annual billing charges 10 months for 12 — the "2 months free" claim. */
export const ANNUAL_MONTHS_CHARGED = 10;

const annual = (monthly: number): number =>
  Math.round(((monthly * ANNUAL_MONTHS_CHARGED) / 12) * 100) / 100;

